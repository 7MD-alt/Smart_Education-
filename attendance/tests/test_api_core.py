class CodeGenTests(APITestCase):
    def test_code_length_and_charset(self):
        for _ in range(50):
            c = generate_seance_code()
            self.assertEqual(len(c), 6)
            self.assertFalse(any(ch in c for ch in "01OI"))  # no ambiguous chars

    def test_codes_are_random(self):
        codes = {generate_seance_code() for _ in range(50)}
        self.assertGreater(len(codes), 40)  # overwhelmingly unique
