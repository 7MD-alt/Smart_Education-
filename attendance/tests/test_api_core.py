# ATTENDANCE INTEGRITY / DANGER ZONE
# ══════════════════════════════════════════════════════════════════════════════

class AttendanceIntegrityTests(BaseData):
    def _absences(self, n):
        for i in range(n):
            AttendanceRecord.objects.create(course=self.course, student=self.student,
                                            date=_local_now().date() - timedelta(days=i + 1),
                                            status="ABSENT")

    def test_danger_zone_aggregation(self):
        self._absences(3)  # max_absences = 3 → in danger
        from attendance.services.novaa_action_executor import attendance_report
        r = attendance_report(self.admin.id, "ADMIN", filiere="IATE")
        self.assertTrue(r["success"])
        self.assertEqual(r["data"]["danger"], 1)
        self.assertEqual(r["data"]["absent"], 3)

    def test_below_threshold_not_danger(self):
        self._absences(2)  # below 3
        from attendance.services.novaa_action_executor import attendance_report
        r = attendance_report(self.admin.id, "ADMIN", filiere="IATE")
        self.assertEqual(r["data"]["danger"], 0)

    def test_unique_attendance_per_seance(self):
        from django.db import IntegrityError, transaction
        s = self._active_seance()
        AttendanceRecord.objects.create(course=self.course, student=self.student, seance=s,
                                        date=s.date, status="PRESENT")
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                AttendanceRecord.objects.create(course=self.course, student=self.student, seance=s,
                                                date=s.date, status="ABSENT")


