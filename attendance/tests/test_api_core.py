class CheckInGuardTests(BaseData):
    def test_checkin_on_completed_seance_rejected(self):
        s = Seance.objects.create(course=self.course, date=_local_now().date(),
                                  start_time=_local_now().time(), status=SeanceStatus.COMPLETED)
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/check-in/", {}, format="multipart")
        self.assertEqual(r.status_code, 400)
        self.assertEqual(r.data.get("reason"), "NOT_ACTIVE")

    def test_checkin_already_checked_in(self):
        s = self._active_seance(code="")  # no code → straight to other guards
        AttendanceRecord.objects.create(course=self.course, student=self.student,
                                        seance=s, date=s.date, status="PRESENT")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/check-in/", {}, format="multipart")
        self.assertEqual(r.status_code, 400)
        self.assertEqual(r.data.get("reason"), "ALREADY_CHECKED_IN")

    def test_checkin_missing_seance_404(self):
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post("/api/student/seances/999999/check-in/", {}, format="multipart")
        self.assertEqual(r.status_code, 404)


