class SeanceCodeTests(BaseData):
    def test_code_autogenerated_on_create(self):
        self.client.force_authenticate(user=self.teacher_user)
        r = self.client.post(f"/api/teacher/courses/{self.course.id}/seances/",
                             {"date": "2030-01-01", "start_time": "10:00"}, format="json")
        self.assertEqual(r.status_code, 201)
        self.assertTrue(r.data[0]["check_in_code"])  # non-empty code returned to teacher

    def test_teacher_supplied_code_used(self):
        self.client.force_authenticate(user=self.teacher_user)
        r = self.client.post(f"/api/teacher/courses/{self.course.id}/seances/",
                             {"date": "2030-01-01", "start_time": "10:00", "check_in_code": "myCode"},
                             format="json")
        self.assertEqual(r.data[0]["check_in_code"], "MYCODE")  # uppercased

    def test_teacher_seance_list_includes_code(self):
        self._active_seance(code="ZZZ999")
        self.client.force_authenticate(user=self.teacher_user)
        r = self.client.get(f"/api/teacher/courses/{self.course.id}/seances/")
        self.assertTrue(any(s.get("check_in_code") == "ZZZ999" for s in r.data))

    def test_student_seance_list_HIDES_code(self):
        self._active_seance(code="SECRET")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.get("/api/student/seances/")
        for s in (r.data if isinstance(r.data, list) else r.data.get("results", [])):
            self.assertNotIn("check_in_code", s)          # code never leaks
            self.assertIn("requires_code", s)             # but the flag is present

    def test_verify_code_correct(self):
        s = self._active_seance(code="GOOD12")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/verify-code/", {"code": "good12"}, format="json")
        self.assertEqual(r.status_code, 200)
        self.assertTrue(r.data["valid"])

    def test_verify_code_wrong(self):
        s = self._active_seance(code="GOOD12")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/verify-code/", {"code": "BAD"}, format="json")
        self.assertEqual(r.status_code, 400)
        self.assertFalse(r.data["valid"])

    def test_checkin_without_code_blocked(self):
        s = self._active_seance(code="NEED11")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/check-in/", {}, format="multipart")
        self.assertEqual(r.status_code, 400)
        self.assertEqual(r.data.get("reason"), "CODE_REQUIRED")

    def test_checkin_wrong_code_blocked(self):
        s = self._active_seance(code="NEED11")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/check-in/", {"code": "NOPE"}, format="multipart")
        self.assertEqual(r.status_code, 400)
        self.assertEqual(r.data.get("reason"), "CODE_INVALID")

    def test_checkin_correct_code_passes_gate(self):
        # Correct code → gate passes → next guard fires (no registered face), proving
        # the code gate let a valid code through.
        s = self._active_seance(code="NEED11")
        self.client.force_authenticate(user=self.student_user)
        r = self.client.post(f"/api/student/seances/{s.id}/check-in/", {"code": "need11"}, format="multipart")
        self.assertEqual(r.data.get("reason"), "NO_REGISTERED_FACE")


